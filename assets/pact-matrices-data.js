function featureByName(name){
  return (classDb.features||[]).find(f=>f.className==='Носитель Договора'&&f.feature===name)||null;
}
function requirementFrom(description){
  const match=String(description||'').match(/(?:\*\*)?Требовани[ея](?:\*\*)?\s*:\s*([^\n]+)/i);
  return match?match[1].replace(/\*+/g,'').trim():'';
}
function minLevelFrom(requirement){
  const match=String(requirement||'').match(/(?:Носитель(?:я)?(?: Договора)?\s*)?(\d+)\s*-?(?:го|й)\s+уров(?:ень|ня)/i);
  return match?Number(match[1]):2;
}
function cloneFeature(name){
  const feature=featureByName(name);
  return feature?{description:String(feature.description||''),category:feature.category||''}:{description:'',category:''};
}

